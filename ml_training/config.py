DATASETS_DIR = PACKAGE_DIR / "datasets"

# Fraud training set, generated by prepare_dataset.py.
FRAUD_DIR = DATASETS_DIR / "fraud"
GENUINE_DIR = FRAUD_DIR / "genuine"
TAMPERED_DIR = FRAUD_DIR / "tampered"
# Known-forgery exemplars you collect by hand; embedded into the Siamese
# reference bank rather than used as classifier training data.
REFERENCE_DIR = FRAUD_DIR / "reference"
MANIFEST_PATH = FRAUD_DIR / "manifest.csv"

# OCR ground truth: one JSON of expected field values per source image.
OCR_DIR = DATASETS_DIR / "ocr"
OCR_LABELS_DIR = OCR_DIR / "labels"
OCR_REPORT_PATH = OCR_DIR / "report.json"

# Field-box templates for ROI extraction (small JSON — safe to commit).
TEMPLATES_DIR = PACKAGE_DIR / "templates"

# Trained weight files consumed by the app via FRAUD_*_WEIGHTS.
MODELS_DIR = PACKAGE_DIR / "saved_models"
CNN_WEIGHTS_PATH = MODELS_DIR / "cnn_tamper.pt"
CNN_METRICS_PATH = MODELS_DIR / "cnn_tamper.metrics.json"
SIAMESE_WEIGHTS_PATH = MODELS_DIR / "siamese_embedder.pt"
SIAMESE_METRICS_PATH = MODELS_DIR / "siamese_embedder.metrics.json"
REFERENCE_BANK_PATH = MODELS_DIR / "reference_embeddings.pt"

DOC_KINDS = ("nic", "proposal")
IMAGE_EXTENSIONS = (".jpg", ".jpeg", ".png", ".webp", ".bmp", ".tif", ".tiff")

# --- Preprocessing ----------------------------------------------------------
# ResNet-18 input size and ImageNet normalization. These mirror
# app/ai/fraud/cnn_classifier.py::_run_inference and
# app/ai/fraud/siamese_detector.py::embed exactly. Change them in one place
# only if you change them in the other.
IMAGE_SIZE = 224
IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]

# --- Dataset synthesis ------------------------------------------------------
SEED = 42
# Variants generated per authentic source image, per class. The tampered count
# is spread across TAMPER_OPS so each forgery style is represented.
AUG_PER_IMAGE = 6
TAMPER_PER_IMAGE = 6
TAMPER_OPS = ("copymove", "splice", "textpatch", "requant")
# Fraction of *source images* (not variants) held out for validation.
VAL_FRACTION = 0.25

# --- CNN tamper classifier --------------------------------------------------
CNN_EPOCHS = 15
CNN_BATCH_SIZE = 16
CNN_LEARNING_RATE = 3e-4
CNN_WEIGHT_DECAY = 1e-4
CNN_PATIENCE = 5  # early-stop after this many epochs without val improvement

# --- Siamese embedder -------------------------------------------------------
SIAMESE_EPOCHS = 20
SIAMESE_BATCH_SIZE = 16
SIAMESE_LEARNING_RATE = 1e-4
SIAMESE_WEIGHT_DECAY = 1e-4
# Cosine-embedding margin: negatives are pushed below this similarity.
SIAMESE_MARGIN = 0.3
