"""Shared paths, hyperparameters, and helpers for the training scripts.

Every script imports from here so that dataset locations and preprocessing
constants are defined exactly once. The normalization constants in particular
**must** stay in step with the inference code in ``app/ai/fraud`` — a model
trained under different normalization silently degrades when the detector runs
it (see :data:`IMAGENET_MEAN`).
"""

