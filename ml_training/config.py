def ensure_dirs() -> None:
    """Create every generated directory (idempotent)."""
    for path in (
        GENUINE_DIR,
        TAMPERED_DIR,
        REFERENCE_DIR,
        OCR_LABELS_DIR,
        TEMPLATES_DIR,
        MODELS_DIR,
    ):
        path.mkdir(parents=True, exist_ok=True)


def set_seed(seed: int = SEED) -> None:
    """Seed Python, NumPy, and torch so a run is reproducible.

    torch is imported lazily: the labelling and calibration scripts need a seed
    but have no reason to pay for the torch import.
    """
    random.seed(seed)
    os.environ["PYTHONHASHSEED"] = str(seed)
    try:
        import numpy as np

        np.random.seed(seed)
    except ImportError:  # pragma: no cover - numpy is a hard dependency
        pass
    try:
        import torch

        torch.manual_seed(seed)
        torch.cuda.manual_seed_all(seed)
    except ImportError:  # pragma: no cover - torch only needed by trainers
        pass


def resolve_device(name: str = "auto"):
    """Return a ``torch.device``; ``"auto"`` prefers CUDA when available."""
    import torch

    if name == "auto":
        name = "cuda" if torch.cuda.is_available() else "cpu"
    return torch.device(name)


def iter_raw_images(doc_kinds=DOC_KINDS):
    """Yield ``(doc_kind, path)`` for every authentic scan under ``RAW_DIR``.

    Images sitting loose in ``RAW_DIR`` (not in a per-kind subfolder) are
    yielded with a doc kind of ``"unknown"`` so they are still usable for fraud
    training, where the document type does not matter.
    """
    if not RAW_DIR.is_dir():
        return

    for kind in doc_kinds:
        folder = RAW_DIR / kind
        if not folder.is_dir():
            continue
        for path in sorted(folder.iterdir()):
            if path.is_file() and path.suffix.lower() in IMAGE_EXTENSIONS:
                yield kind, path

    for path in sorted(RAW_DIR.iterdir()):
        if path.is_file() and path.suffix.lower() in IMAGE_EXTENSIONS:
            yield "unknown", path


def build_eval_transform():
    """Deterministic transform matching what the detectors do at inference."""
    from torchvision import transforms

    return transforms.Compose(
        [
            transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
            transforms.ToTensor(),
            transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ]
    )


def build_train_transform():
    """Eval transform plus mild jitter that does not fake tampering artifacts.

    Deliberately conservative: aggressive colour or geometric augmentation here
    would either mask the compression artifacts the classifier needs to see, or
    invent new ones. Content-level variation is baked into the dataset by
    ``prepare_dataset.py`` instead.
    """
    from torchvision import transforms

    return transforms.Compose(
        [
            transforms.Resize((IMAGE_SIZE, IMAGE_SIZE)),
            transforms.ColorJitter(brightness=0.1, contrast=0.1, saturation=0.05),
            transforms.ToTensor(),
            transforms.Normalize(mean=IMAGENET_MEAN, std=IMAGENET_STD),
        ]
    )
